#!/usr/bin/env node
// Writes app/state/zstd-snapshot.js: the ZSTD community feed this build ships with.
//
// The feed is read from disk at launch (state/catalog.js applies whatever the last launch kept),
// so a console updating to a new build would list nothing ZSTD until its first fetch, 25 seconds
// later — and never at all when the console is offline. The shipped snapshot fills that first
// launch: state/zstd-feed.js feedForLaunch picks the newer of the kept feed and this one.
//
// Run it before a release, whenever the community feed should be refreshed in the build. The page
// is fetched over the network and parsed with the app's own parser, so what is written here is
// exactly what a launch would have kept, checks included.
import {register} from 'node:module';
import {writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const app = resolve(root, 'app');
const out = resolve(app, 'state/zstd-snapshot.js');
const url = 'https://raw.githubusercontent.com/FrancoVoid9/zstd-catalog/main/index.html';

// The app modules import @ps5-react/core for native APIs this tool never calls: the tests' loader
// stubs it out. Everything else is the app's own code, unchanged.
register(pathToFileURL(resolve(app, 'state/download-queue-test-loader.mjs')).href, pathToFileURL(`${root}/`).href);
const {itemsOf, valid} = await import(pathToFileURL(resolve(app, 'state/zstd-feed.js')).href);

const response = await fetch(url, {headers: {Accept: 'text/html,application/xhtml+xml', 'User-Agent': 'Padrino Store'}});
if (!response.ok) throw new Error(`zstd-snapshot: HTTP ${response.status}`);
const page = await response.text();
const items = itemsOf(page);
if (!items.length) throw new Error('zstd-snapshot: the page has no ITEMS');
const feed = {format: 1, generated: new Date().toISOString(), items};
if (!valid(feed)) throw new Error('zstd-snapshot: the feed failed its checks');

const text = `// Generated by tools/zstd-snapshot.mjs: the ZSTD community feed this build ships with, so a
// console that has never kept one (a first launch after an update, an offline console) still lists
// it before anything has been fetched. state/zstd-feed.js feedForLaunch picks the newer of this and
// the feed on disk. Regenerate before a release; do not edit.

var snapshot = ${JSON.stringify(feed)};

export { snapshot };
`;

writeFileSync(out, text);
console.log(`zstd-snapshot: wrote ${items.length} items to app/state/zstd-snapshot.js`);
