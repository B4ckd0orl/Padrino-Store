#!/usr/bin/env node
// Writes app/data/formats.js: each game's package formats, as Browse's filter groups them.
//
// The format is a release's own (data/releases/<id>.json), and the library counts every game at once
// while the app reads a release file only when a game opens. This copies the groups into one module
// the filter loads with the catalog. A game left out of it is "unknown": its sources say only "binary".
//
// Run it after the importers, before a build. --check writes nothing and exits 1 when the file is stale.
//
// The releases go through the app's own cache (state/release-cache.js), so paused hosts, DLC packs and
// patch-only files are left out exactly as they are on the console.
import {register} from 'node:module';
import {readdirSync, readFileSync, writeFileSync, existsSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const app = resolve(root, 'app');
const out = resolve(app, 'data/formats.js');

// The app modules import @ps5-react/core for native APIs this tool never calls: the tests' loader
// stubs it out. Everything else is the app's own code, unchanged.
register(pathToFileURL(resolve(app, 'state/download-queue-test-loader.mjs')).href, pathToFileURL(`${root}/`).href);
const {createReleaseCache} = await import(pathToFileURL(resolve(app, 'state/release-cache.js')).href);
const {formatsOf, UNKNOWN} = await import(pathToFileURL(resolve(app, 'state/formats.js')).href);

const cache = createReleaseCache((path) => readFileSync(resolve(app, path), 'utf8'));
const files = readdirSync(resolve(app, 'data/releases')).filter((name) => name.endsWith('.json')).sort();

const index = {};
for (const name of files) {
  const releases = cache(`data/releases/${name}`);
  const formats = formatsOf(releases).filter((value) => value !== UNKNOWN);
  if (formats.length) index[name.replace(/\.json$/i, '')] = formats;
}
const text = `// Generated by tools/formats-index.mjs: each game's package formats, as Browse's filter groups
// them. A game left out says only "binary" in every source: the drawer calls it "unknown".

var formats = ${JSON.stringify(index)};

export { formats };
`;

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current !== text) {
    console.error(`formats-index: app/data/formats.js is stale, run "node tools/formats-index.mjs"`);
    process.exit(1);
  }
  console.log(`formats-index: up to date (${Object.keys(index).length} games)`);
} else {
  writeFileSync(out, text);
  console.log(`formats-index: wrote ${Object.keys(index).length} games to app/data/formats.js`);
}
